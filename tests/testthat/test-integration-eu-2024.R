test_that('preserved EU 2024 sources implement complete fixed final results', {
 root<-Sys.getenv('SWEELECTIONS_EU2024_ROOT')
 skip_if(!nzchar(root),'Preserved EU 2024 sources not configured')
 x<-results(2024,election='E',source='local',data_dir=root)
 expect_equal(sum(x$votes),4198011L);expect_true(all(x$total_votes==4240459L))
 expect_true(all(x$blank_votes==33733L));expect_true(all(x$invalid_votes==42448L))
 d<-results(2024,election='E',level='district',source='local',data_dir=root,detail='full')
 u<-d[!duplicated(d$district_code),]
 expect_equal(nrow(u),6589L);expect_equal(sum(u$district_type=='uppsamlingsdistrikt'),314L)
 expect_true(all(is.na(u$eligible_voters[u$district_type=='uppsamlingsdistrikt'])))
 kd<-candidacies(2024,election='E',source='local',data_dir=root,detail='full')
 expect_equal(nrow(kd),1395L);expect_equal(sum(kd$valid),1390L)
 expect_false('1203'%in%kd$candidate_number)
 c<-candidates(2024,election='E',source='local',data_dir=root)
 expect_equal(length(unique(c$candidate_number)),1340L)
 e<-elected(2024,election='E',source='local',data_dir=root)
 expect_equal(nrow(e),21L);expect_equal(sum(e$total_preference_votes),sum(c$total_preference_votes[c$elected]))
 s<-substitutes(2024,election='E',source='local',data_dir=root)
 expect_equal(nrow(s),77L);expect_equal(length(unique(s$substitute_candidate_number)),27L)
 p<-preference_votes(2024,election='E',level='district',by_list=TRUE,source='local',data_dir=root)
 expect_equal(nrow(p),393607L);expect_equal(sum(p$preference_votes),1914494L)
 expect_false(anyDuplicated(p[c('district_code','party_code','candidate_number','list_number')])>0L)
 expect_true(all(is.na(p$qualified_by_preference_votes)))
})
